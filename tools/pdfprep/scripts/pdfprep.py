#!/usr/bin/env python3
"""Local PDF preparation. No model API calls; source files are never modified."""
from __future__ import annotations

import argparse
from contextlib import redirect_stdout
import csv
from datetime import datetime, timezone
import hashlib
from importlib.metadata import version as package_version
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
from urllib.parse import quote

VERSION = "0.1.0"
SCHEMA = "local-pdfprep/1"


def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def write_json(path: Path, value) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def link(path: str) -> str:
    return quote(path, safe="/-._~#=")


def bbox(rect) -> list[float]:
    return [round(float(v), 3) for v in rect]


def engine_info() -> dict:
    return {p: package_version(p) for p in ("PyMuPDF", "pymupdf4llm")}


def ocr_identity(language: str) -> dict:
    executable = shutil.which("tesseract")
    if not executable:
        return {"available": False}
    # Version and language data affect OCR and therefore the cache key.
    identity = {"available": True, "executable": executable, "language": language}
    for name, args in (("version", ["--version"]), ("languages", ["--list-langs"])):
        result = subprocess.run([executable, *args], capture_output=True, text=True, timeout=15)
        identity[name] = result.stdout + result.stderr
    return identity


def cache_valid(dest: Path, source_hash: str, signature: dict) -> bool:
    try:
        data = json.loads((dest / "extraction.json").read_text(encoding="utf-8"))
        if (data.get("schema") != SCHEMA or data.get("source", {}).get("sha256") != source_hash
                or data.get("signature") != signature or not data.get("files")):
            return False
        for name, expected in data["files"].items():
            path = dest / name
            if not path.resolve().is_relative_to(dest.resolve()) or not path.is_file():
                return False
            if digest(path) != expected:
                return False
        return True
    except (OSError, ValueError, TypeError, KeyError):
        return False


def check_destination(source: Path, dest: Path, source_hash: str) -> None:
    if source.is_relative_to(dest):
        raise ValueError("Output cannot contain the source PDF; choose another directory.")
    if dest.is_symlink():
        raise ValueError(f"Refusing a symlink output directory: {dest}")
    if not dest.exists():
        return
    try:
        data = json.loads((dest / "extraction.json").read_text(encoding="utf-8"))
        owned = data.get("schema") == SCHEMA
        same = (data.get("source", {}).get("path") == str(source)
                or data.get("source", {}).get("sha256") == source_hash)
    except (OSError, ValueError, TypeError):
        owned = same = False
    if not owned or not same:
        raise ValueError(f"Refusing to replace an unrelated output directory: {dest}")
    known = set(data.get("files", {})) | {"extraction.json"}
    extras = [str(p.relative_to(dest)) for p in dest.rglob("*")
              if p.is_file() and str(p.relative_to(dest)) not in known]
    if extras:
        raise ValueError(f"Output contains files not generated by pdfprep; move them before rebuilding: {extras[:5]}")


def run_ocr(page, stage: Path, language: str) -> str:
    executable = shutil.which("tesseract")
    if not executable:
        raise RuntimeError("Tesseract is not installed; OCR was not performed.")
    with tempfile.TemporaryDirectory(prefix=".ocr-", dir=stage) as scratch:
        image = Path(scratch) / "page.png"
        page.get_pixmap(dpi=300, alpha=False).save(str(image))
        result = subprocess.run(
            [executable, str(image), "stdout", "-l", language],
            capture_output=True, text=True, timeout=180, check=False,
        )
        if result.returncode:
            raise RuntimeError(f"Tesseract failed: {result.stderr.strip()[:400]}")
        return result.stdout.strip()


def extract_page(doc, number: int, stage: Path, args, header_info) -> dict:
    import pymupdf
    with redirect_stdout(io.StringIO()):
        import pymupdf4llm
    # This pinned Markdown helper changes a process-wide glyph setting at
    # import. Restore normal bounding boxes before CSV/text extraction; without
    # this, decimals and minus signs can be split into separate table lines.
    pymupdf.TOOLS.unset_quad_corrections(False)

    page = doc[number]
    stem = f"page-{number + 1:04d}"
    warnings = []
    native = page.get_text("text", sort=True)
    needs_ocr = len(re.sub(r"\s", "", native)) < 40
    use_ocr = args.ocr == "always" or (args.ocr == "auto" and needs_ocr)
    text = native
    method = "native"
    if use_ocr:
        try:
            text = run_ocr(page, stage, args.language)
            method = "ocr"
            warnings.append("OCR text is unverified; tables are not reconstructed from OCR.")
        except (RuntimeError, OSError, subprocess.SubprocessError) as exc:
            warnings.append(str(exc))
            method = "native-ocr-failed"
    elif needs_ocr:
        warnings.append("Very little native text; page may be a scan, a figure or blank. OCR disabled.")
    if not text.strip():
        warnings.append("No searchable text was extracted; inspect the page image.")
    if "\ufffd" in text or "\x00" in text:
        warnings.append("Invalid Unicode in extracted text; consider --ocr always.")

    (stage / "pages" / f"{stem}.txt").write_text(text, encoding="utf-8")
    page_image = f"pages/{stem}.png"
    page.get_pixmap(dpi=args.dpi, alpha=False).save(str(stage / page_image))

    # Preserve native geometric evidence even when Markdown reading order is wrong.
    blocks = [{"bbox": bbox(b[:4]), "text": b[4], "block_number": b[5]}
              for b in page.get_text("blocks", sort=True) if b[6] == 0]
    figures = []
    try:
        regions = [("raster", pymupdf.Rect(item["bbox"])) for item in page.get_image_info()]
        regions += [("vector", rect) for rect in page.cluster_drawings()]
        seen = set()
        for kind, rect in regions:
            rect = rect & page.rect * page.derotation_matrix
            # Tiny fragments stay available in the full page. Never claim these
            # automatically detected crops are complete semantic figures.
            key = tuple(round(x, 1) for x in rect)
            if rect.is_empty or rect.width < 18 or rect.height < 18 or key in seen:
                continue
            seen.add(key)
            if len(figures) >= 100:
                warnings.append("More than 100 graphic regions; remaining regions retained in page image only.")
                break
            name = f"figures/{stem}-{kind}-{len(figures) + 1:03d}.png"
            # clip coordinates for rendering follow page rotation.
            clip = rect * page.rotation_matrix
            page.get_pixmap(clip=clip, dpi=args.dpi, alpha=False).save(str(stage / name))
            figures.append({"kind": kind, "bbox": bbox(rect), "image": name})
    except Exception as exc:
        warnings.append(f"Graphic region extraction failed: {type(exc).__name__}: {exc}")

    tables = []
    if method != "ocr":
        try:
            finder = page.find_tables(strategy=args.table_strategy)
            for i, table in enumerate(finder.tables, 1):
                rows = table.extract()
                if len(rows) < 2 or table.col_count < 2:
                    continue
                name = f"tables/{stem}-table-{i:03d}"
                with (stage / f"{name}.csv").open("w", encoding="utf-8", newline="") as stream:
                    csv.writer(stream).writerows(rows)
                rect = pymupdf.Rect(table.bbox)
                if table.header.external:
                    rect |= pymupdf.Rect(table.header.bbox)
                page.get_pixmap(clip=rect * page.rotation_matrix, dpi=args.dpi, alpha=False).save(str(stage / f"{name}.png"))
                tables.append({"bbox": bbox(table.bbox), "crop_bbox": bbox(rect), "csv": f"{name}.csv", "image": f"{name}.png",
                               "rows": rows, "row_count": len(rows), "column_count": table.col_count,
                               "header": {"names": table.header.names, "external": table.header.external,
                                          "bbox": bbox(table.header.bbox)},
                               "verified": False})
        except Exception as exc:
            warnings.append(f"Table extraction failed: {type(exc).__name__}: {exc}")
    if tables:
        warnings.append("Detected tables are unverified; check headers, units, footnotes and merged cells against the page.")

    if method == "ocr":
        markdown = text + "\n"
    else:
        try:
            # No images here: our explicit region links avoid absolute temporary
            # filenames and preserve the original page as the authoritative view.
            # The helper removes page rotation in memory. Use a separate handle
            # so page images, geometry and metadata share one coordinate system.
            with pymupdf.open(stage / "original.pdf") as layout_doc, redirect_stdout(io.StringIO()):
                markdown = pymupdf4llm.to_markdown(
                    layout_doc, pages=[number], hdr_info=header_info, write_images=False,
                    margins=0, fontsize_limit=0, table_strategy=args.table_strategy,
                    force_text=True, show_progress=False,
                )
        except Exception as exc:
            warnings.append(f"Markdown layout extraction failed; using plain text: {type(exc).__name__}: {exc}")
            markdown = text + "\n"
    label = page.get_label() or str(number + 1)
    # Single-page Markdown lives in pages/, combined Markdown lives at root.
    prefix = f"## PDF page {number + 1} (label {label})\n\n[Page image]({page_image}) · [Original PDF](original.pdf#page={number + 1})\n\n"
    extras = []
    for i, item in enumerate(tables, 1):
        extras.append(f"Table {i}: [CSV]({item['csv']}) · [crop]({item['image']})")
    for i, item in enumerate(figures, 1):
        extras.append(f"![Graphic region {i}, {item['kind']}, PDF page {number + 1}]({item['image']})")
    if warnings:
        extras.append("Extraction notes:\n" + "\n".join(f"- {w}" for w in warnings))
    combined = prefix + markdown.strip() + "\n\n" + "\n\n".join(extras) + "\n"
    local = re.sub(r"\]\(((?:pages|tables|figures)/[^)]+|original\.pdf[^)]*)\)",
                   lambda m: "](" + link("../" + m[1]) + ")", combined)
    (stage / "pages" / f"{stem}.md").write_text(local, encoding="utf-8")
    return {"page": number + 1, "label": label, "rotation": page.rotation,
            "size_points": [page.rect.width, page.rect.height], "method": method,
            "native_characters": len(native), "extracted_characters": len(text),
            "needs_review": bool(warnings), "warnings": warnings, "text_blocks": blocks,
            "markdown": f"pages/{stem}.md", "text": f"pages/{stem}.txt", "image": page_image,
            "figures": figures, "tables": tables, "combined_markdown": combined}


def extract(source: Path, stage: Path, args, signature: dict, source_hash: str) -> dict:
    import pymupdf
    pymupdf.no_recommend_layout()
    with redirect_stdout(io.StringIO()):
        import pymupdf4llm
    pymupdf.TOOLS.unset_quad_corrections(False)

    for sub in ("pages", "figures", "tables"):
        (stage / sub).mkdir()
    shutil.copyfile(source, stage / "original.pdf")
    # Extract the immutable copy, so the source cannot change underneath us.
    if digest(stage / "original.pdf") != source_hash:
        raise ValueError("Source changed during copying; retry when writing has finished.")
    with pymupdf.open(stage / "original.pdf") as doc:
        if doc.needs_pass:
            raise ValueError("Password-protected PDF: provide a locally decrypted copy.")
        if not doc.is_pdf or not doc.page_count:
            raise ValueError("Input is not a nonempty PDF.")
        with redirect_stdout(io.StringIO()):
            header_info = pymupdf4llm.IdentifyHeaders(doc)
        pages = [extract_page(doc, n, stage, args, header_info) for n in range(doc.page_count)]
        metadata = dict(doc.metadata or {})
        toc = doc.get_toc()
    header = (f"# {source.name}\n\n"
              "Local extraction; verify mathematical notation and material table values against the original.\n\n"
              "[Original PDF](original.pdf) · [Extraction report](report.md)\n\n")
    (stage / "document.md").write_text(header + "\n---\n\n".join(p.pop("combined_markdown") for p in pages), encoding="utf-8")
    summary = {"pages": len(pages), "tables": sum(len(p["tables"]) for p in pages),
               "graphic_regions": sum(len(p["figures"]) for p in pages),
               "ocr_pages": [p["page"] for p in pages if p["method"] == "ocr"],
               "review_pages": [p["page"] for p in pages if p["needs_review"]]}
    report = [f"# Extraction report: {source.name}", "", f"Pages: {summary['pages']}; detected tables: {summary['tables']}; graphic regions: {summary['graphic_regions']}.", "",
              "Extraction is unverified. Markdown reading order and heading detection are heuristic. Equations are not converted to verified LaTeX. Borderless tables may be missed. Figure crops may be fragments. All pages and the byte-identical original remain available.", "",
              "CSV values are strings, not inferred types. Empty cells may represent merged cells. Table header metadata is in extraction.json; surrounding captions and footnotes remain in page text and images. OCR text does not produce structured tables.", "",
              "PDF page numbers below are one-based; printed labels may differ.", ""]
    for p in pages:
        report.append(f"- [Page {p['page']}]({p['markdown']}): {p['method']}, {p['extracted_characters']} characters, {len(p['tables'])} tables.")
        report.extend(f"  - {warning}" for warning in p["warnings"])
    (stage / "report.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    data = {"schema": SCHEMA, "created_utc": datetime.now(timezone.utc).isoformat(),
            "source": {"path": str(source), "name": source.name, "sha256": source_hash},
            "signature": signature, "summary": summary, "metadata": metadata,
            "toc": toc, "pages": pages,
            "files": {str(p.relative_to(stage)): digest(p) for p in sorted(stage.rglob("*")) if p.is_file()}}
    write_json(stage / "extraction.json", data)
    return data


def prepare(source: Path, dest: Path, args, signature: dict) -> tuple[str, dict]:
    source_hash = digest(source)
    check_destination(source, dest, source_hash)
    dest.parent.mkdir(parents=True, exist_ok=True)
    lock = dest.with_name("." + dest.name + ".pdfprep-lock")
    try:
        lock.mkdir()
    except FileExistsError:
        raise ValueError(f"Output is locked: {lock}. If no pdfprep process is running, remove this empty lock directory.") from None
    stage = backup = None
    try:
        # Recheck under the lock in case another process just finished.
        check_destination(source, dest, source_hash)
        if not args.force and cache_valid(dest, source_hash, signature):
            return "CACHED", json.loads((dest / "extraction.json").read_text(encoding="utf-8"))
        stage = Path(tempfile.mkdtemp(prefix=f".{dest.name}.building-", dir=dest.parent))
        data = extract(source, stage, args, signature, source_hash)
        if dest.exists():
            backup = Path(tempfile.mkdtemp(prefix=f".{dest.name}.previous-", dir=dest.parent))
            backup.rmdir()
            dest.rename(backup)
        try:
            stage.rename(dest)
            stage = None
        except BaseException:
            if backup:
                backup.rename(dest)
                backup = None
            raise
        if backup:
            shutil.rmtree(backup)
            backup = None
        return "READY", data
    finally:
        if stage and stage.exists():
            shutil.rmtree(stage)
        lock.rmdir()


def prepared_ancestor(path: Path, root: Path) -> bool:
    for parent in path.parents:
        if (parent / "extraction.json").is_file():
            return True
        if parent == root:
            break
    return False


def jobs_for(args) -> list[tuple[Path, Path]]:
    inputs = [Path(p).expanduser().resolve() for p in args.inputs]
    single = len(inputs) == 1 and inputs[0].is_file()
    output = Path(args.output).expanduser().absolute() if args.output else None
    jobs = []
    seen = set()
    for source in inputs:
        if not source.exists():
            raise ValueError(f"Input does not exist: {source}")
        if source.is_file():
            if source.suffix.lower() != ".pdf":
                raise ValueError(f"Not a PDF filename: {source}")
            if single:
                dest = output or source.with_name(source.stem + ".prepared")
            else:
                root = output or Path.cwd() / "pdfprep-output"
                # Distinguish explicitly supplied files with identical basenames.
                suffix = hashlib.sha256(str(source).encode()).hexdigest()[:8]
                dest = root / f"{source.stem}-{suffix}"
            candidates = [(source, dest)]
        elif source.is_dir():
            root = output or source.with_name(source.name + ".prepared")
            if len(inputs) > 1:
                suffix = hashlib.sha256(str(source).encode()).hexdigest()[:8]
                root = root / f"{source.name}-{suffix}"
            files = source.rglob("*") if args.recursive else source.glob("*")
            candidates = [(p.resolve(), root / p.relative_to(source).with_suffix(""))
                          for p in sorted(files) if p.is_file() and p.suffix.lower() == ".pdf"
                          and not p.is_relative_to(root) and not prepared_ancestor(p, source)]
        else:
            raise ValueError(f"Unsupported input: {source}")
        for file, dest in candidates:
            # Resolve parents but retain a symlink at the destination for refusal.
            dest = dest.parent.resolve() / dest.name
            if file not in seen:
                jobs.append((file, dest))
                seen.add(file)
    if not jobs:
        raise ValueError("No PDFs found. Use --recursive to include subdirectories.")
    destinations = [dest for _, dest in jobs]
    if len(set(destinations)) != len(destinations):
        raise ValueError("Two inputs map to the same output; process them separately.")
    for source, _ in jobs:
        if any(source.is_relative_to(dest) for dest in destinations):
            raise ValueError("An output would contain an input PDF; choose another output directory.")
    for a in destinations:
        if any(a != b and a.is_relative_to(b) for b in destinations):
            raise ValueError("Output packages would overlap; choose another output directory.")
    return jobs


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", nargs="*", help="Local PDF files or folders")
    parser.add_argument("--output", "-o", help="Single PDF: package directory; folders/multiple inputs: collection root")
    parser.add_argument("--recursive", "-r", action="store_true", help="Search subdirectories")
    parser.add_argument("--force", action="store_true", help="Rebuild this tool's existing package")
    parser.add_argument("--ocr", choices=("auto", "never", "always"), default="auto", help="Default: auto, attempt OCR on pages with little native text")
    parser.add_argument("--language", default="eng", help="Tesseract language(s), e.g. eng+ita")
    parser.add_argument("--dpi", type=int, default=120, help="Page/figure resolution, 72-300 (default: 120)")
    parser.add_argument("--table-strategy", choices=("lines_strict", "lines", "text"), default="lines_strict", help="Use text for borderless tables; may produce false detections")
    parser.add_argument("--doctor", action="store_true", help="Show local dependencies and OCR availability")
    parser.add_argument("--version", action="version", version=f"pdfprep {VERSION}")
    args = parser.parse_args(argv)
    try:
        engines = engine_info()
        if args.doctor:
            print(json.dumps({"pdfprep": VERSION, "python": sys.executable, "engines": engines,
                              "ocr": ocr_identity(args.language), "model_api": False}, indent=2))
            return 0
        if not args.inputs:
            parser.error("supply at least one PDF or folder, or use --doctor")
        if not 72 <= args.dpi <= 300:
            parser.error("--dpi must be between 72 and 300")
        jobs = jobs_for(args)
        signature = {"version": VERSION, "implementation_sha256": digest(Path(__file__)),
                     "engines": engines, "dpi": args.dpi, "ocr": args.ocr,
                     "language": args.language, "table_strategy": args.table_strategy,
                     "ocr_engine": ocr_identity(args.language) if args.ocr != "never" else None}
        failures = 0
        for source, dest in jobs:
            print(f"PROCESS {source}", flush=True)
            try:
                status, data = prepare(source, dest, args, signature)
                summary = data["summary"]
                print(f"{status} {dest} ({summary['pages']} pages, {summary['tables']} tables, {len(summary['review_pages'])} pages flagged for review)", flush=True)
            except Exception as exc:
                failures += 1
                print(f"ERROR {source}: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1 if failures else 0
    except (OSError, ValueError, subprocess.SubprocessError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    except ModuleNotFoundError as exc:
        print(f"ERROR: missing dependency: {exc}. Reinstall local-pdfprep.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
